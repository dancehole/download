  function getLang() {
    return localStorage.getItem("lang") === "en" ? "en" : "zh";
  }
  function setLang(l) {
    localStorage.setItem("lang", l === "en" ? "en" : "zh");
  }
  function t(key, vars) {
    const lang = getLang();
    let s = (DICT[lang] && DICT[lang][key]) || (DICT.zh && DICT.zh[key]) || key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.split("{" + k + "}").join(vars[k]);
      });
    }
    return s;
  }

